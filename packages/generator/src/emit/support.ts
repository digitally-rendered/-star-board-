import { BUILD_VERSION } from '../version.js';

/** One emitted file; `path` is relative to the output root and uses `/` separators. */
export interface GeneratedFile {
  path: string;
  contents: string;
}

export interface Source {
  title: string;
  version: string;
}

export function header(source: Source): string {
  return `// GENERATED by @star-board/generator ${BUILD_VERSION} from ${source.title}@${source.version} — do not edit`;
}

/** Joins lines with LF and a single trailing newline; blank runs are collapsed to one. */
export function lines(parts: readonly (string | null | false)[]): string {
  const out: string[] = [];
  for (const part of parts) {
    if (part === null || part === false) continue;
    for (const line of part.split('\n')) {
      if (line === '' && out[out.length - 1] === '') continue;
      out.push(line);
    }
  }
  while (out[out.length - 1] === '') out.pop();
  return `${out.join('\n')}\n`;
}

export function indent(text: string, depth = 1): string {
  const pad = '  '.repeat(depth);
  return text
    .split('\n')
    .map((line) => (line === '' ? line : pad + line))
    .join('\n');
}

/** Stable JSON: object keys are written in sorted order at every level. */
export function stableJson(value: unknown): string {
  return `${JSON.stringify(sortDeep(value), null, 2)}\n`;
}

function sortDeep(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortDeep);
  if (typeof value === 'object' && value !== null) {
    const record = value as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(record).sort()) out[key] = sortDeep(record[key]);
    return out;
  }
  return value;
}

/** `/** … *\/` with the text escaped so it can never close the comment early. */
export function docComment(text: string, depth = 0): string {
  const safe = text.replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim();
  return indent(`/** ${safe} */`, depth);
}
