import { describe, expect, it } from 'vitest';
import { BUILD_VERSION, generate, manifestOf, plan, type GeneratedFile } from '../src/index.js';
import { petstore, petstoreWithCustomOperations } from './fixture.js';

const OPTS = { out: 'src/generated', features: 'src/features' };
const HEADER = `// GENERATED by @star-board/generator ${BUILD_VERSION} from petstore@2026.10.0 — do not edit`;

function file(files: readonly GeneratedFile[], path: string): string {
  const found = files.find((f) => f.path === path);
  if (!found) throw new Error(`no generated file ${path}`);
  return found.contents;
}

describe('golden output for fixtures/petstore.json', () => {
  const model = petstore();
  const files = generate(model, OPTS);

  it('emits the expected file list', async () => {
    await expect(files.map((f) => f.path).join('\n')).toMatchFileSnapshot(
      './__snapshots__/files.txt.snap',
    );
  });

  it('matches the plan snapshot', async () => {
    await expect(JSON.stringify(plan(model), null, 2)).toMatchFileSnapshot(
      './__snapshots__/plan.json.snap',
    );
  });

  it.each([
    'domain/pet/types.ts',
    'domain/pet/schemas.ts',
    'application/pet/usePetActions.ts',
    'application/pet/usePetScreens.ts',
    'domain/pet/PetListScreen.tsx',
    'domain/pet/PetCreateScreen.tsx',
    'adapters/paths.ts',
    'registry.ts',
    'routes.tsx',
    'nav.ts',
    'i18n.defaults.json',
    'manifest.json',
  ])('matches the snapshot of %s', async (path) => {
    await expect(file(files, path)).toMatchFileSnapshot(
      `./__snapshots__/${path.replace(/\//g, '__')}.snap`,
    );
  });

  it('stamps every code file with the header and ends every file with one LF', () => {
    for (const f of files) {
      expect(f.contents.endsWith('\n'), f.path).toBe(true);
      expect(f.contents.endsWith('\n\n'), f.path).toBe(false);
      expect(f.contents.includes('\r'), f.path).toBe(false);
      if (!f.path.endsWith('.json')) expect(f.contents.startsWith(HEADER), f.path).toBe(true);
    }
  });

  it('registers one generated screen per (schema, operation) and nothing else', () => {
    const registry = file(files, 'registry.ts');
    const registrations = registry.match(/registry\.register\(/g) ?? [];
    expect(registrations).toHaveLength(5);
    expect(registry).not.toMatch(/key: 'field\./);
    expect(registry).not.toMatch(/key: 'action\./);
    expect(registry).toContain("key: 'screen.grid', schema: 'pet', target: 'available_pets_query'");
  });

  it('hides the action when the capability is missing and keeps screens off fetching', () => {
    const screens = file(files, 'application/pet/usePetScreens.ts');
    expect(screens).toContain('if (can.pet_create) actions.push(');
    expect(screens).toContain('if (can.pet_delete) {');
    expect(screens).toContain('.mutateAsync({ id, doc: versionedOf(entity) })');
    expect(screens).toContain('ifMatch: etagFor(entity),');
    for (const f of files.filter((g) => g.path.startsWith('domain/'))) {
      expect(f.contents, f.path).not.toMatch(/useEntity|useEntityList|useView|useMutation|fetch\(/);
    }
  });

  it('applies the platform rules of typescript/05 to the forms and tables', () => {
    const create = file(files, 'domain/pet/PetCreateScreen.tsx');
    const edit = file(files, 'domain/pet/PetEditScreen.tsx');
    const list = file(files, 'domain/pet/PetListScreen.tsx');
    const routes = file(files, 'routes.tsx');
    const i18n = JSON.parse(file(files, 'i18n.defaults.json')) as Record<string, string>;
    // §4 regulated wording: an empty disclaimer key per form, rendered through help.inline when set.
    expect(i18n['pet.screen.create.disclaimer']).toBe('');
    expect(i18n['pet.screen.edit.disclaimer']).toBe('');
    for (const form of [create, edit]) {
      expect(form).toContain("useResolved<HelpProps>('help.inline', 'pet'");
      expect(form).toMatch(/const disclaimer = t\('pet\.screen\.(create|edit)\.disclaimer'\);/);
      expect(form).toContain('dirty: boolean;');
    }
    // §9 unsaved changes: the create and edit containers hold navigation and release it on save.
    expect(routes.match(/useUnsavedChanges\(props\.dirty\)/g)).toHaveLength(2);
    expect(routes).toContain(
      "useOptionalResolved<UnsavedChangesDialogProps>('screen.custom', 'pet', 'unsaved-changes')",
    );
    expect(routes).toContain('unsaved.release(() => void navigate(`/pet/${created.entity_id}`))');
    expect(routes).toContain('unsaved.release(() => void navigate(`/pet/${id}`))');
    expect(routes).not.toMatch(/PetListRoute\(\): ReactElement \{[^}]*unsaved/);
    expect(file(files, 'domain/contract.ts')).toContain('export function useOptionalResolved<P>(');
    // §6 mobile: the table screens resolve the renderer's body at target `table` and hand it
    // `compact` (the body renders the card list under the breakpoint) with the page-object prefix.
    expect(list).toContain(
      "const Table = useResolved<ListProps<Pet>>('screen.list', 'pet', 'table');",
    );
    expect(list).toContain('compact={props.compact}');
    expect(list).toContain('testIdPrefix="pet-list"');
    expect(list).not.toContain('<table');
    expect(file(files, 'domain/pet/PetGridScreen.tsx')).toContain(
      "useResolved<ListProps<Partial<Pet>>>('screen.grid', 'pet', 'table')",
    );
    expect(file(files, 'application/pet/usePetScreens.ts')).toContain(
      'const compact = useCompactLayout();',
    );
    // Cancel and back go through the resolved `action.custom`, so an app restyles them per schema.
    expect(create).toContain("useResolved<ActionProps>('action.custom', 'pet', 'cancel')");
    expect(create).toContain('testId="pet-create-cancel"');
    expect(file(files, 'domain/pet/PetDetailScreen.tsx')).toContain(
      "useResolved<ActionProps>('action.custom', 'pet', 'back')",
    );
    // Defaults and validation wording: the create form starts from the schema defaults, and zod
    // issues are worded through the validation keys with the field label.
    const hooks = file(files, 'application/pet/usePetScreens.ts');
    expect(hooks).toContain(
      "export const PET_CREATE_DEFAULTS: Partial<PetCreate> = { 'status': 'available' };",
    );
    expect(hooks).toContain('dirty: isDirty(values, PET_CREATE_DEFAULTS),');
    expect(hooks).toContain('setErrors(fieldErrors(parsed.error.issues, t, labels));');
    expect(i18n['validation.required']).toBe('{label} is required');
    expect(file(files, 'application/support.ts')).toContain('export function messageForIssue(');
    // Unknown routes and thrown errors render inside the app frame through the resolved states.
    expect(routes).toContain("{ path: '*', element: <NotFoundRoute /> }");
    expect(routes).toContain('errorElement: <RouteErrorRoute />');
    expect(routes).toContain("useResolved<StateProps>('state.empty', '*', 'not-found')");
    // §7 i18n: components read `t` from the provider, so a locale switch reaches them.
    for (const screen of [create, edit, list, file(files, 'domain/pet/PetDetailScreen.tsx')]) {
      expect(screen).toContain('const t = useT();');
      expect(screen).not.toContain('import { t }');
    }
    expect(file(files, 'i18n.ts')).toContain('export function useT(): T {');
  });

  it('places the agent affordance slot on the create and edit screens only', () => {
    expect(file(files, 'domain/pet/PetCreateScreen.tsx')).toContain('<AgentPanelSlot');
    expect(file(files, 'domain/pet/PetEditScreen.tsx')).toContain('<AgentPanelSlot');
    expect(file(files, 'domain/pet/PetListScreen.tsx')).not.toContain('AgentPanelSlot');
    expect(file(files, 'domain/AgentPanelSlot.tsx')).toContain(
      "'screen.custom', schema, 'agent-panel'",
    );
  });

  it('is deterministic: two runs are deep-equal and the manifest hashes are stable', () => {
    const again = generate(petstore(), OPTS);
    expect(again).toEqual(files);
    const manifest = JSON.parse(file(files, 'manifest.json')) as {
      buildVersion: string;
      files: { path: string; sha256: string }[];
    };
    expect(manifest.buildVersion).toBe(BUILD_VERSION);
    expect(manifest.files).toEqual(
      manifestOf(again, { title: 'petstore', version: '2026.10.0' }).files,
    );
    expect(manifest.files.map((f) => f.path)).toEqual(
      files.filter((f) => f.path !== 'manifest.json').map((f) => f.path),
    );
  });

  it('omits the json defaults and the runtime i18n with i18n: false', () => {
    const without = generate(model, { ...OPTS, i18n: false });
    expect(without.some((f) => f.path === 'i18n.defaults.json')).toBe(false);
    expect(file(without, 'i18n.ts')).not.toContain('createI18n');
    expect(file(without, 'i18n.ts')).toContain("'pet.field.name.label': 'Name'");
  });

  it('calls the configured renderer in the setup file', () => {
    expect(file(files, 'setup.ts')).toContain("from '@star-board/renderer-mui'");
    expect(file(generate(model, { ...OPTS, renderer: '@acme/renderer' }), 'setup.ts')).toContain(
      "from '@acme/renderer'",
    );
  });
});

describe('Tier 3 operations', () => {
  const files = generate(petstoreWithCustomOperations(), OPTS);

  it('emits a stub screen, a route and an action hook per custom operation', () => {
    const paths = files.map((f) => f.path);
    expect(paths).toContain('domain/pet/PetAdoptScreen.generated.tsx');
    expect(paths).toContain('domain/pet/PetRenameScreen.generated.tsx');
    expect(paths).toContain('domain/pet/PetOwnerScreen.generated.tsx');
    const routes = file(files, 'routes.tsx');
    expect(routes).toContain("path: '/pet/:id/adopt'");
    expect(routes).toContain("path: '/pet/:id/owner'");
    const actions = file(files, 'application/pet/usePetActions.ts');
    expect(actions).toContain('export function usePetAdopt()');
    expect(actions).toContain('export function usePetRename()');
    expect(actions).toContain(
      "useMutation<operations['pet_rename']['body'], operations['pet_rename']['response']>('pet_rename')",
    );
    expect(actions).not.toContain('usePetOwner()');
    expect(file(files, 'registry.ts')).toContain(
      "key: 'screen.custom', schema: 'pet', target: 'pet_adopt'",
    );
  });

  it('offers the custom item action on the detail screen behind its capability', () => {
    expect(file(files, 'application/pet/usePetScreens.ts')).toContain(
      "if (can.pet_adopt) actions.push({ operationId: 'pet_adopt'",
    );
    expect(file(files, 'domain/pet/PetDetailScreen.tsx')).toContain(
      "useResolved<ActionProps>('action.custom', 'pet', 'pet_adopt')",
    );
  });
});
